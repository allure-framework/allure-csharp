namespace Allure.Model;

/// <summary>
/// Provides standard Allure link type values.
/// </summary>
public static class LinkType
{
    /// <summary>
    /// Represents a generic link.
    /// </summary>
    public const string Link = "link";

    /// <summary>
    /// Represents a link to an issue tracker item.
    /// </summary>
    public const string Issue = "issue";

    /// <summary>
    /// Represents a link to an item in a test management system.
    /// </summary>
    public const string TmsItem = "tms";
}
